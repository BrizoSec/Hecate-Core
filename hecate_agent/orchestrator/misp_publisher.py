import logging
import os
import httpx
from typing import List


def _setting(name: str, default: str = "") -> str:
    """Read a credential or endpoint from the environment (loaded from .env by the CLI).

    Never hardcode these: the values below were once committed and pushed.
    """
    return os.environ.get(name, default)


def _misp_verify_tls() -> bool:
    """Verify MISP's certificate unless MISP_VERIFY_SSL=false (e.g. a local self-signed instance)."""
    return _setting("MISP_VERIFY_SSL", "true").lower() != "false"

logger = logging.getLogger(__name__)


def publish_hunt_to_misp(topic: str, hypothesis: str, observables: List[str]) -> str:
    """
    Creates a new Event in MISP for the completed Hunt and attaches the observables.
    """
    url = f"{_setting('MISP_BASE_URL', 'https://localhost:8443')}/events/add"
    headers = {
        "Authorization": _setting("MISP_API_KEY"),
        "Accept": "application/json",
        "Content-Type": "application/json"
    }
    
    attributes = []
    
    # Very basic parsing of observables to determine MISP attribute types
    for obs in observables:
        obs = obs.strip()
        attr_type = "text"
        
        # Simple heuristics for MISP types
        if len(obs) in (32, 40, 64) and all(c in "0123456789abcdefABCDEF" for c in obs):
            if len(obs) == 32:
                attr_type = "md5"
            elif len(obs) == 40:
                attr_type = "sha1"
            elif len(obs) == 64:
                attr_type = "sha256"
        elif obs.count(".") == 3 and all(p.isdigit() for p in obs.split(".")):
            attr_type = "ip-dst"
        elif obs.startswith("http"):
            attr_type = "url"
        elif "." in obs and " " not in obs:
            attr_type = "domain"
            
        attributes.append({
            "type": attr_type,
            "value": obs,
            "comment": "Auto-extracted by Hecate LangGraph Pipeline",
            "to_ids": True
        })
        
    # Add the Hypothesis itself as an internal comment
    attributes.append({
        "type": "comment",
        "value": hypothesis,
        "comment": "Hunt Hypothesis generated by Hecate",
        "to_ids": False
    })
    
    payload = {
        "Event": {
            "info": f"Hecate Hunt: {topic}",
            "distribution": "0", # Organization only
            "threat_level_id": "3", # Low
            "analysis": "2", # Completed
            "Attribute": attributes
        }
    }
    
    try:
        resp = httpx.post(url, headers=headers, json=payload, verify=_misp_verify_tls(), timeout=10.0)
        if resp.status_code == 200:
            event_id = resp.json().get("Event", {}).get("id", "Unknown")
            return f"Successfully created MISP Event #{event_id}"
        else:
            return f"MISP API returned {resp.status_code}: {resp.text}"
    except Exception as e:
        return f"Failed to publish to MISP: {e}"
